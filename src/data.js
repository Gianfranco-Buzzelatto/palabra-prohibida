function buildCards(groups) {
  const seen = new Set();
  const cards = [];
  for (const [cat, words] of Object.entries(groups)) {
    for (const raw of words) {
      const w = raw.trim();
      const key = w.toLowerCase();
      if (!w || seen.has(key)) continue;
      seen.add(key);
      cards.push({ w, cat });
    }
  }
  return cards.map((c, i) => ({ ...c, id: i }));
}

